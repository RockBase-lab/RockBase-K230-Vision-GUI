def _assets_dir():
    """Asset directory, derived from this module's __file__ (apps/'s parent is gui/).

    Deriving it from here rather than from an audio module keeps it correct when
    those modules move between packages.
    """
    path = globals().get("__file__")
    if path:
        try:
            base = path.rsplit("/", 1)[0]        # .../gui/apps
            return base.rsplit("/", 1)[0] + "/assets"
        except BaseException:
            pass
    return "/sdcard/factory/gui/assets"


def _load_png(path):
    try:
        f = open(path, "rb")
        data = f.read()
        f.close()
        return lv.img_dsc_t({"data_size": len(data), "data": data})
    except BaseException:
        return None


def _timer_imgs():
    if _TIMER_IMGS:
        return _TIMER_IMGS
    base = _assets_dir()
    for ch in "0123456789":
        dsc = _load_png(base + "/timer_" + ch + ".png")
        if dsc is not None:
            _TIMER_IMGS[ch] = dsc
    dsc = _load_png(base + "/timer_colon.png")
    if dsc is not None:
        _TIMER_IMGS[":"] = dsc
    return _TIMER_IMGS


def _btn_img(name):
    """Button bitmap cache. The data inside dsc must stay referenced, so it lives in a
    module dict to survive GC."""
    dsc = _BTN_IMGS.get(name)
    if dsc is None:
        dsc = _load_png(_assets_dir() + "/" + name + ".png")
        _BTN_IMGS[name] = dsc
    return dsc


def _fmt_mmss(seconds):
    s = int(seconds)
    if s < 0:
        s = 0
    m = s // 60
    if m > 99:
        m = 99
    return "{:02d}{:02d}".format(m, s % 60)


def _safe_font(obj, *names):
    """Some font_montserrat_N names in this binding are functions rather than lv_font_t,
    and calling set_style_text_font raises "Can't convert function" for them. Try each
    candidate in turn."""
    for name in names:
        f = getattr(lv, name, None)
        if f is None:
            continue
        try:
            obj.set_style_text_font(f, 0)
            return
        except BaseException:
            continue


