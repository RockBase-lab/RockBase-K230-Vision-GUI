class AudioApp:
    def __init__(self, content, ctx):
        self.ctx = ctx
        self.state = STATE_IDLE
        self.rec = device.DmicRecorder()
        self.player = device.WavPlayer()
        self.finalizer = None

        self.duration = 0.0        # recorded length (seconds)
        self.gain = 1.0            # playback normalisation gain
        self.last_refresh = 0
        self._t0 = 0               # recording/playback start (wall-clock ticks_ms)
        self._timer_text = None
        self._error = ""
        self._dead = False         # True after destroy(): controls are gone, never touch them again
        self.pager = None          # paging.DragPager (built in _build)

        # ---- Page 2 sweep state ----
        self.tone = tone.ToneOut()
        self.tone_running = False
        self._freq_val = 1000          # raw frequency slider value (logarithmic mapping)
        self._amp_val = 300            # raw amplitude slider value (mV)
        self._last_readout = ""

        content.set_style_bg_color(lv.color_hex(APP_BG), 0)
        content.set_style_bg_opa(lv.OPA.COVER, 0)
        content.set_style_pad_all(0, 0)
        content.clear_flag(lv.obj.FLAG.SCROLLABLE)

        self._build(content)

        # Entering the app **always starts at IDLE / page 1**.
        self.ctx.set_back_handler(self._on_back)

    # ---------------- UI ----------------
    def _build(self, content):
        # ---- Top indicator dots (fixed, they do not scroll with the page) ----
        self.dots = []
        dot_row = lv.obj(content)
        dot_row.set_size(CONTENT_W, DOT_H)
        dot_row.align(lv.ALIGN.TOP_MID, 0, DOTS_TOP)
        dot_row.set_style_bg_opa(lv.OPA.TRANSP, 0)
        dot_row.set_style_border_width(0, 0)
        dot_row.clear_flag(lv.obj.FLAG.SCROLLABLE)
        dot_row.set_flex_flow(lv.FLEX_FLOW.ROW)
        dot_row.set_flex_align(lv.FLEX_ALIGN.CENTER, lv.FLEX_ALIGN.CENTER,
                               lv.FLEX_ALIGN.CENTER)
        dot_row.set_style_pad_all(0, 0)
        dot_row.set_style_pad_column(DOT_GAP, 0)
        for di in range(PAGE_COUNT):
            dot = lv.obj(dot_row)
            self._set_dot_style(dot, di == PAGE_REC)
            self.dots.append(dot)

        # ---- Horizontal paging container ----
        # No flex + native scrolling: native scrolling is clamped at both ends and cannot
        # page circularly; and the "drag half-way, then decide on release" judgement has to be
        # computed here anyway. DragPager moves the pages itself.
        self.wrap = lv.obj(content)
        self.wrap.set_size(CONTENT_W, CONTENT_H)
        self.wrap.align(lv.ALIGN.TOP_MID, 0, 0)
        self.wrap.set_style_bg_opa(lv.OPA.TRANSP, 0)
        self.wrap.set_style_border_width(0, 0)
        self.wrap.set_style_pad_all(0, 0)
        self.wrap.clear_flag(lv.obj.FLAG.SCROLLABLE)

        self.page1 = lv.obj(self.wrap)
        self.page1.set_size(CONTENT_W, CONTENT_H)
        self.page1.set_style_bg_opa(lv.OPA.TRANSP, 0)
        self.page1.set_style_border_width(0, 0)
        self.page1.set_style_pad_all(0, 0)
        self.page1.clear_flag(lv.obj.FLAG.SCROLLABLE)

        self.page2 = lv.obj(self.wrap)
        self.page2.set_size(CONTENT_W, CONTENT_H)
        self.page2.set_style_bg_opa(lv.OPA.TRANSP, 0)
        self.page2.set_style_border_width(0, 0)
        self.page2.set_style_pad_all(0, 0)
        self.page2.clear_flag(lv.obj.FLAG.SCROLLABLE)

        # circular=True: swiping left from the last page returns to page 1, and swiping right
        # from the first page goes to the last (user requirement, same as IMU). blocked is
        # described by _drag_blocked.
        self.pager = paging.DragPager(
            (self.page1, self.page2), CONTENT_W, circular=True,
            on_page_changed=self._on_page_changed,
            blocked=self._drag_blocked)

        self._build_rec_page(self.page1)
        self._build_tone_page(self.page2)

        self._apply_state(STATE_IDLE)
        self._update_tone_readout()

    # ---------- Page 1: record/playback ----------
    def _build_rec_page(self, page):
        imgs = _timer_imgs()
        total_w = sum(SLOT_WIDTHS)
        self.timer_slots = []
        x = -total_w // 2
        for slot, sw in enumerate(SLOT_WIDTHS):
            im = lv.img(page)
            im.set_size(sw, TIMER_H)
            dsc = imgs.get(":") if slot == 2 else imgs.get("0")
            if dsc is not None:
                im.set_src(dsc)
            im.align(lv.ALIGN.TOP_MID, x + sw // 2, TIMER_TOP)
            self.timer_slots.append(im)
            x += sw

        self.sub = lv.label(page)
        self.sub.set_text("")
        self.sub.set_style_text_color(lv.color_hex(COL_DIM), 0)
        _safe_font(self.sub, "font_montserrat_16", "font_montserrat_14")
        self.sub.align(lv.ALIGN.TOP_MID, 0, SUB_TOP)

        self.bar = lv.bar(page)
        self.bar.set_size(BAR_W, BAR_H)
        self.bar.align(lv.ALIGN.TOP_MID, 0, BAR_TOP)
        self.bar.set_range(0, 1000)
        self.bar.set_value(0, lv.ANIM.OFF)
        self.bar.set_style_radius(BAR_H // 2, 0)
        self.bar.set_style_bg_color(lv.color_hex(COL_BAR_BG), 0)
        self.bar.set_style_bg_opa(lv.OPA.COVER, 0)
        self.bar.set_style_border_width(0, 0)
        self.bar.set_style_pad_all(0, 0)
        try:
            self.bar.set_style_bg_color(lv.color_hex(COL_RED), lv.PART.INDICATOR)
            self.bar.set_style_radius(BAR_H // 2, lv.PART.INDICATOR)
        except BaseException:
            pass

        self.btn = lv.btn(page)
        self.btn.set_size(BTN_W, BTN_H)
        self.btn.align(lv.ALIGN.TOP_MID, 0, BTN_TOP)
        self.btn.set_style_bg_opa(lv.OPA.TRANSP, 0)
        self.btn.set_style_border_width(0, 0)
        self.btn.set_style_shadow_width(0, 0)
        self.btn.set_style_pad_all(0, 0)
        self.btn.set_style_radius(BTN_RADIUS, 0)
        beep.on_click(self.btn, self._on_click)
        self.btn_img = lv.img(self.btn)
        self.btn_img.center()
        self.btn_img.add_flag(lv.obj.FLAG.CLICKABLE)
        beep.on_click(self.btn_img, self._on_click)

        self.again = lv.label(page)
        self.again.set_text("record again")
        # Use clickable blue instead of grey text: in READY it is the only secondary action,
        # and stacked with the grey hint below it reads as "two lines of explanation".
        self.again.set_style_text_color(lv.color_hex(0x60A5FA), 0)
        _safe_font(self.again, "font_montserrat_16", "font_montserrat_14")
