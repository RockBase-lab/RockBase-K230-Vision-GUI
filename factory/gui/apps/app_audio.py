# Audio app: two pages (horizontal swipe paging, same gesture/threshold as the desktop).
#
#   Page 1 (default) record -> playback (120 s cap):
#     IDLE      [REC]   -> start recording
#     RECORDING [STOP]  -> stop and save (or stop automatically once 120 s is reached)
#     READY     [PLAY]  -> play back; the small "record again" text below re-records
#     PLAYING   [STOP]  -> stop playback
#   Page 2 sweep signal (quantitative amplifier analysis): frequency/amplitude sliders
#     plus START/STOP; the generator lives in audio/tone.py.
#
# Paging: dragging right-to-left goes to the next page (paging.SnapPager, same 120 px
# threshold as the desktop). Two dots at the top indicate the current page.
#
# Audio hardware is exclusive: both pages share the codec output stream. Switching pages
# stops the *other* page's output (leaving page 1 stops playback, leaving page 2 stops the
# sweep tone); the two streams must never be open at the same time. Recording is on the
# input side and does not conflict with output, but leaving page 1 while recording stops it
# too, to avoid inconsistent state.
# CANCEL goes back layer by layer: page 2 -> page 1 -> exit app.
#
# Keys:
#   OK      = page 1 acts like tapping the main button; page 2 toggles START/STOP
#   CANCEL  = page 2 -> back to page 1; page 1 recording/playing -> stop; otherwise exit
#
# The large timer digits are bitmaps (generated by tools/gen_audio_assets.py); the reason is
# in that script's comments: under RENDER_MODE.FULL tiny_ttf re-rasterises every frame and
# cannot be used for permanently visible text.

