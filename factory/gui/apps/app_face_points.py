# Points app: full-screen live 106-point face landmark mesh (det -> landmark).
#
# Second stage of the Face group: Faces answers where the faces are, Points draws
# the structure of the largest one as an even triangle mesh with a dot on every
# vertex. The topology is fixed; only the vertex positions follow the face.
#
# Triangulating the landmark points themselves does not work, because the model
# puts points on the silhouette and on the features and none inside the cheeks.
# The mesh is therefore 26 nodes placed evenly and bound to three landmarks by
# inverse-distance weights, so the topology is fixed and only positions move.
#
# Cost is set by the edge count, not the node count: measured at 800x480 under
# FULL render on a 220x270 face, 23 edges 11.9 ms, 46 edges 19.3 ms, 92 edges
# 30.6 ms, and node dots add about 1.2 ms for 42. Edge width barely matters
# (30.6 ms at 1 px against 31.2 ms at 2 px), so reduce edges rather than width.
#
# The affine rebuild costs 5.78 ms per call, so it runs every other frame and the
# previous points are reused in between; the landmark inference is 1.32 ms.

