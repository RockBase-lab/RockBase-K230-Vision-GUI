# Even triangle mesh, generated offline from one real detection.
#
# Triangulating the landmark points themselves does not work: the 106-point model
# puts points on the silhouette and on the features and nothing inside the
# cheeks, so a Delaunay on them leaves the cheeks empty and packs triangles onto
# the eyes and mouth. Nor does an automatic lattice below about 30 nodes: the
# landmark outline is unevenly spaced and the lower face has no landmarks, so the
# triangles become long and skewed and the eyes vanish into them.
#
# The mesh is therefore 26 nodes placed by hand at even fractions of the face
# box, connected once by Delaunay, and bound to landmarks by inverse-distance
# weights:
#   x = sum(w_i * lm[i_i])  over three nearest landmarks
# The topology never changes; only the node positions follow the face.
#
